use std::env;
use std::fs;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=native_host_exports.def");
    println!("cargo:rustc-link-arg-cdylib=/DEF:native_host_exports.def");

    let exports = read_exports(Path::new("native_host_exports.def"));
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is not set");
    let output_path = Path::new(&out_dir).join("proxy_exports.rs");

    let mut generated = String::new();
    generated.push_str("// Generated by build.rs from native_host_exports.def.\n");
    generated.push_str("// Do not edit this file directly.\n\n");
    generated.push_str(&format!(
        "const EXPECTED_PROXY_EXPORT_COUNT: usize = {};\n\n",
        exports.len()
    ));

    for export in &exports {
        generated.push_str(&format!(
            "proxy_export!({}, PROXY_{});\n",
            export.name, export.name
        ));
    }

    generated.push_str("\nunsafe fn load_proxy_exports(module: Hmodule) {\n");
    generated.push_str("    let mut resolved = 0usize;\n");
    generated.push_str("    macro_rules! load_export {\n");
    generated.push_str("        ($name:literal, $slot:ident) => {\n");
    generated.push_str("            if load_proxy_export(module, $name, addr_of_mut!($slot)) {\n");
    generated.push_str("                resolved += 1;\n");
    generated.push_str("            }\n");
    generated.push_str("        };\n");
    generated.push_str("    }\n\n");

    for export in &exports {
        generated.push_str(&format!(
            "    load_export!(b\"{}\\0\", PROXY_{});\n",
            export.name, export.name
        ));
    }

    generated.push_str("\n    if !module.is_null() {\n");
    generated.push_str("        STATE.proxy_resolved_export_count.store(resolved, std::sync::atomic::Ordering::SeqCst);\n");
    generated.push_str("        STATE.proxy_missing_export_count.store(\n");
    generated.push_str("            EXPECTED_PROXY_EXPORT_COUNT.saturating_sub(resolved),\n");
    generated.push_str("            std::sync::atomic::Ordering::SeqCst,\n");
    generated.push_str("        );\n");
    generated.push_str("    }\n");
    generated.push_str("}\n");

    fs::write(output_path, generated).expect("failed to write generated proxy exports");
}

struct Export {
    name: String,
    ordinal: usize,
}

fn read_exports(path: &Path) -> Vec<Export> {
    let definition = fs::read_to_string(path).expect("failed to read native_host_exports.def");
    let mut in_exports = false;
    let mut exports = Vec::new();

    for (line_number, raw_line) in definition.lines().enumerate() {
        let line = raw_line.split(';').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }

        if line.eq_ignore_ascii_case("EXPORTS") {
            in_exports = true;
            continue;
        }

        if !in_exports {
            continue;
        }

        let mut parts = line.split_whitespace();
        let name = parts
            .next()
            .unwrap_or_else(|| panic!("missing export name at line {}", line_number + 1));
        let ordinal = parts.next().unwrap_or_else(|| {
            panic!(
                "missing ordinal for export {name} at line {}",
                line_number + 1
            )
        });

        let Some(ordinal) = ordinal.strip_prefix('@') else {
            panic!(
                "expected @ordinal for export {name} at line {}",
                line_number + 1
            );
        };

        if !name.chars().all(|c| c == '_' || c.is_ascii_alphanumeric()) {
            panic!(
                "export {name} is not a valid Rust identifier at line {}",
                line_number + 1
            );
        }

        let ordinal = ordinal.parse::<usize>().unwrap_or_else(|_| {
            panic!(
                "invalid ordinal for export {name} at line {}",
                line_number + 1
            )
        });

        exports.push(Export {
            name: name.to_string(),
            ordinal,
        });
    }

    if exports.is_empty() {
        panic!("native_host_exports.def did not define any exports");
    }

    for (index, export) in exports.iter().enumerate() {
        let expected = index + 1;
        if export.ordinal != expected {
            panic!(
                "export {} has ordinal {}, expected contiguous ordinal {}",
                export.name, export.ordinal, expected
            );
        }
    }

    exports
}
